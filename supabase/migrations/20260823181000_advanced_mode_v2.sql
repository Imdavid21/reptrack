-- Advanced Mode V2 is opt-in and additive. Existing fitness rows are untouched.

create table if not exists public.advanced_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  enabled boolean not null default false,
  specialization_muscles text[] not null default '{}',
  session_volume_modifier numeric(4,2) not null default 1.00 check (session_volume_modifier between 0.50 and 1.50),
  updated_at timestamptz not null default now()
);

create table if not exists public.gym_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  bar_weight_kg numeric(6,2) not null default 20 check (bar_weight_kg >= 0 and bar_weight_kg <= 100),
  plates_kg numeric[] not null default array[25,20,15,10,5,2.5,1.25]::numeric[],
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, name)
);

create unique index if not exists gym_profiles_one_default_per_user
  on public.gym_profiles(user_id) where is_default;

create table if not exists public.training_blocks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  focus text,
  starts_on date not null default current_date,
  ends_on date,
  status text not null default 'active' check (status in ('planned','active','completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on is null or ends_on >= starts_on)
);

create index if not exists training_blocks_user_dates
  on public.training_blocks(user_id, starts_on desc);

create table if not exists public.training_experiments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 100),
  metric text not null check (char_length(metric) between 1 and 80),
  baseline numeric,
  target numeric,
  starts_on date not null default current_date,
  ends_on date,
  status text not null default 'active' check (status in ('planned','active','completed','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on is null or ends_on >= starts_on)
);

create index if not exists training_experiments_user_status
  on public.training_experiments(user_id, status, starts_on desc);

create table if not exists public.coach_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null check (char_length(event_type) between 1 and 80),
  event_date date not null default current_date,
  dedupe_key text,
  payload jsonb not null default '{}'::jsonb,
  consumed_at timestamptz,
  created_at timestamptz not null default now(),
  unique(user_id, dedupe_key)
);

create index if not exists coach_events_unconsumed
  on public.coach_events(user_id, consumed_at, created_at desc);

alter table public.advanced_settings enable row level security;
alter table public.gym_profiles enable row level security;
alter table public.training_blocks enable row level security;
alter table public.training_experiments enable row level security;
alter table public.coach_events enable row level security;

create policy "advanced_settings_own" on public.advanced_settings
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "gym_profiles_own" on public.gym_profiles
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "training_blocks_own" on public.training_blocks
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "training_experiments_own" on public.training_experiments
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "coach_events_own" on public.coach_events
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
